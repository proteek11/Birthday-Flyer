echo html_writer::tag('span', $hassharedimage ? get_string('thoughtimageactivebadge', 'local_birthdayflyer') : get_string('thoughtimageaddbadge', 'local_birthdayflyer'), ['class' => 'employeemgmt-thought-image-badge']);
